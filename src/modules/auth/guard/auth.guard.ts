import { Injectable } from '@nestjs/common';
import type { CanActivate, ExecutionContext } from '@nestjs/common';
import { Reflector } from '@nestjs/core';

import { PUBLIC_ROUTE_KEY } from '../../../common/decorator/public.decorator.js';
import type { AuthenticatedRequest } from '../../../common/type/authenticatedRequest.js';
import { UserRepository } from '../../users/repository/user.repository.js';
import { SessionService } from '../service/session.service.js';
import { AuthValidator } from '../validation/auth.validation.js';

/**
 * Authenticates requests using the sessions stored in Redis.
 */
@Injectable()
export class AuthGuard implements CanActivate {
    constructor(
        private readonly reflector: Reflector,
        private readonly sessionService: SessionService,
        private readonly userRepository: UserRepository,
        private readonly authValidator: AuthValidator

    ) { }

    /**
     * Allows public routes or requests with a valid user session.
     */
    async canActivate(context: ExecutionContext): Promise<boolean> {
        const isPublic = this.reflector.getAllAndOverride<boolean>(
            PUBLIC_ROUTE_KEY,
            [context.getHandler(), context.getClass()],

        );

        if (isPublic == true) {
            return true;
        }

        const request = context
            .switchToHttp()
            .getRequest<AuthenticatedRequest>();

        const token = this.extractToken(request.headers.authorization);

        if (token === null) {
            throw this.authValidator.invalidToken();
        }

        const userId = await this.sessionService.validateToken(token);

        if (userId == null) {
            throw this.authValidator.invalidToken();
        }

        // Reject session whose user no longer exists.
        const user = await this.userRepository.findById(userId);

        if (user === null) {
            throw this.authValidator.invalidToken();
        }

        request.userId = user.id;

        return true;

    }

    /**
     * Extracts a token matching the format generated by SessionService.
     */
    private extractToken(authorization: string | undefined): string | null {
        if (authorization === undefined) {
            return null;
        }

        // Mathc "Bearer <token", where the token contains exactly 64 hexadecimal
        // characters, as generated by randomBytes(32).toString('hex').
        // The parantheses capture the token without the "Bearer" prefix.
        const match = /^Bearer +([0-9a-f]{64})$/i.exec(authorization);

        // Return the captured token, or null if the header format is invalid
        // Session validity is checked seperately in Redis.
        return match?.[1] ?? null;
    }

}